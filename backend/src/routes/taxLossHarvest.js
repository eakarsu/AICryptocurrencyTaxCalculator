const express = require('express');
const { TaxLossHarvest } = require('../models');
const auth = require('../middleware/auth');
const { callOpenRouter } = require('../services/openRouterService');
const router = express.Router();

router.get('/', auth, async (req, res) => {
  try {
    const items = await TaxLossHarvest.findAll({ where: { userId: req.userId }, order: [['unrealizedLoss', 'DESC']] });
    res.json(items);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.get('/:id', auth, async (req, res) => {
  try {
    const item = await TaxLossHarvest.findOne({ where: { id: req.params.id, userId: req.userId } });
    if (!item) return res.status(404).json({ error: 'Not found' });
    res.json(item);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.post('/', auth, async (req, res) => {
  try {
    const item = await TaxLossHarvest.create({ ...req.body, userId: req.userId });
    res.status(201).json(item);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.put('/:id', auth, async (req, res) => {
  try {
    const item = await TaxLossHarvest.findOne({ where: { id: req.params.id, userId: req.userId } });
    if (!item) return res.status(404).json({ error: 'Not found' });
    await item.update(req.body);
    res.json(item);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.delete('/:id', auth, async (req, res) => {
  try {
    const item = await TaxLossHarvest.findOne({ where: { id: req.params.id, userId: req.userId } });
    if (!item) return res.status(404).json({ error: 'Not found' });
    await item.destroy();
    res.json({ message: 'Deleted successfully' });
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.post('/ai/opportunities', auth, async (req, res) => {
  try {
    const items = await TaxLossHarvest.findAll({ where: { userId: req.userId } });
    const result = await callOpenRouter(
      `Analyze these cryptocurrency holdings for tax-loss harvesting opportunities:\n${JSON.stringify(items)}\n\nProvide: 1) Best candidates for harvesting 2) Estimated tax savings 3) Wash sale rule considerations (crypto-specific) 4) Replacement asset suggestions 5) Timing recommendations 6) Year-end strategy`,
      'You are an expert in tax-loss harvesting strategies for cryptocurrency. Identify optimal harvesting opportunities while considering wash sale rules and market conditions.'
    );
    res.json({ analysis: result.content, model: result.model, usage: result.usage });
  } catch (error) { res.status(500).json({ error: error.message }); }
});

module.exports = router;
