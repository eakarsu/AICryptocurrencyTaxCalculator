const express = require('express');
const { CrossBorderTax } = require('../models');
const auth = require('../middleware/auth');
const { callOpenRouter } = require('../services/openRouterService');
const router = express.Router();

router.get('/', auth, async (req, res) => {
  try {
    const items = await CrossBorderTax.findAll({ where: { userId: req.userId }, order: [['date', 'DESC']] });
    res.json(items);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.get('/:id', auth, async (req, res) => {
  try {
    const item = await CrossBorderTax.findOne({ where: { id: req.params.id, userId: req.userId } });
    if (!item) return res.status(404).json({ error: 'Not found' });
    res.json(item);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.post('/', auth, async (req, res) => {
  try {
    const item = await CrossBorderTax.create({ ...req.body, userId: req.userId });
    res.status(201).json(item);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.put('/:id', auth, async (req, res) => {
  try {
    const item = await CrossBorderTax.findOne({ where: { id: req.params.id, userId: req.userId } });
    if (!item) return res.status(404).json({ error: 'Not found' });
    await item.update(req.body);
    res.json(item);
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.delete('/:id', auth, async (req, res) => {
  try {
    const item = await CrossBorderTax.findOne({ where: { id: req.params.id, userId: req.userId } });
    if (!item) return res.status(404).json({ error: 'Not found' });
    await item.destroy();
    res.json({ message: 'Deleted successfully' });
  } catch (error) { res.status(500).json({ error: error.message }); }
});

router.post('/ai/analyze', auth, async (req, res) => {
  try {
    const items = await CrossBorderTax.findAll({ where: { userId: req.userId } });
    const result = await callOpenRouter(
      `Analyze these cross-border cryptocurrency transactions for international tax compliance:\n${JSON.stringify(items)}\n\nProvide: 1) Tax treaty implications 2) FBAR filing requirements 3) FATCA reporting obligations 4) Double taxation avoidance strategies 5) Country-specific tax rules 6) Currency conversion tax implications`,
      'You are an expert in international cryptocurrency taxation. Analyze cross-border transactions and provide compliance guidance for multiple jurisdictions.'
    );
    res.json({ analysis: result.content, model: result.model, usage: result.usage });
  } catch (error) { res.status(500).json({ error: error.message }); }
});

module.exports = router;
